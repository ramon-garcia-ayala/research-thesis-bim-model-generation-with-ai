// The 3D model for a presentation: the pipeline's source and rebuilt projects, in metres, with what did not come back
// the same. Reads ../pipeline/out/{source,rebuilt,diff}.json (run the pipeline, or just `python compare.py`, first) and
// writes presentations/thesis/presentacion-04/model.json, or the folder of `--deck=<id>`, whose doors and windows also
// carry the id of their host wall (the pitch draws those relations). Simplified geometry: walls are boxes of a fixed thickness
// (the JSON has no wall widths), floors are 30 cm slabs, doors and windows are panels sized from their type name.
// Kept per element so each side can show its own value: wall length, room area (m², 0 when not enclosed), and the
// hand of each door and window.
//
//   node scripts/deck-model.mjs
//   node scripts/deck-model.mjs --deck=presentacion-06

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(HERE, '../../pipeline/out')
const DEFAULT_DECK = 'presentacion-04'
const FT = 0.3048
const load = (name) => JSON.parse(readFileSync(join(OUT, name), 'utf8'))
const r = (v) => Math.round(v * 1000) / 1000

/** "0915 x 2134mm" → [0.915, 2.134]; a fallback when the type name has no size. */
function sizeOf(type, fallback) {
  const m = /(\d+)\s*x\s*(\d+)\s*mm/i.exec(type?.[1] ?? '')
  return m ? [Number(m[1]) / 1000, Number(m[2]) / 1000] : fallback
}

/** A pipeline project as a model for the slides. `withHost`: each door and window also holds `host`, its wall's id. */
export function project(p, { withHost = false } = {}) {
  const level = Object.fromEntries(p.levels.map((l) => [l.name, l.elevation * FT]))
  const walls = p.walls.map((w) => {
    const [a, b] = w.curve.p
    return {
      id: w.id,
      a: [r(a[0] * FT), r(a[1] * FT)],
      b: [r(b[0] * FT), r(b[1] * FT)],
      z: r((level[w.base_level] ?? 0) + w.base_offset * FT),
      h: r(w.height * FT),
      len: r(w.length * FT),
      curtain: w.curtain,
    }
  })
  const dirOf = new Map(
    walls.map((w) => {
      const dx = w.b[0] - w.a[0]
      const dy = w.b[1] - w.a[1]
      const len = Math.hypot(dx, dy) || 1
      return [w.id, [r(dx / len), r(dy / len)]]
    }),
  )
  const opening = (fallback) => (o) => {
    const [w, h] = sizeOf(o.type, fallback)
    return {
      id: o.id,
      p: o.point.map((v) => r(v * FT)),
      w,
      h,
      dir: dirOf.get(o.host) ?? [1, 0],
      hand: !!o.hand_flipped,
      ...(withHost ? { host: o.host } : {}),
    }
  }
  return {
    levels: p.levels.map((l) => ({ name: l.name, z: r(l.elevation * FT) })),
    walls,
    floors: p.floors.map((f) => ({
      id: f.id,
      z: r(f.loops[0][0].p[0][2] * FT),
      pts: f.loops[0].map((c) => [r(c.p[0][0] * FT), r(c.p[0][1] * FT)]),
    })),
    doors: p.doors.map(opening([0.9, 2.1])),
    windows: p.windows.map(opening([0.9, 1.2])),
    rooms: p.rooms.map((room) => ({ id: room.id, p: room.point.map((v) => r(v * FT)), a: r(Math.max(room.area, 0) * FT * FT) })),
  }
}

/** Per side, element id → its issues: `{ source: { id: [issue] }, rebuilt: { id: [issue] } }`. */
function issues(diff) {
  const out = { source: {}, rebuilt: {} }
  const add = (side, id, issue) => (out[side][id] ??= []).push(issue)
  for (const list of Object.values(diff))
    for (const d of list) {
      if (d.id != null) add('source', d.id, d.issue)
      if (d.rebuilt_id != null) add('rebuilt', d.rebuilt_id, d.issue)
    }
  return out
}

function main() {
  const named = process.argv.find((a) => a.startsWith('--deck='))?.slice('--deck='.length)
  const withHost = named != null
  const target = resolve(HERE, `../presentations/thesis/${named ?? DEFAULT_DECK}/model.json`)
  const model = {
    note: 'Generated by scripts/deck-model.mjs from pipeline/out. Metres; Revit X, Y in plan and Z up.',
    source: project(load('source.json'), { withHost }),
    rebuilt: project(load('rebuilt.json'), { withHost }),
    issues: issues(load('diff.json')),
  }
  writeFileSync(target, JSON.stringify(model) + '\n')
  const counts = Object.fromEntries(Object.entries(load('diff.json')).map(([k, v]) => [k, v.length]))
  console.log(`wrote ${target}`, counts)
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main()
