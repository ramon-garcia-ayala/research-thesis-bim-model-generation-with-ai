// The public site (GitHub Pages): one deck and what it needs to run on its own, nothing else of the repo.
//
//   node scripts/build-pages.mjs [outDir]        (default: ../_site, from research-map/)
//
// Writes `<outDir>/assets/` (the decks' code, styles and three.js), `<outDir>/thesis/<deck>/` (the deck page and its
// data), the map's `theme.js` (the one file the decks import from outside `presentations/`), a `site.js` cut down to this deck, and an `index.html` that opens it. The map, the papers, the reading notes,
// the other decks and the pipeline stay out: only this deck is published, though the repository is public.
// The deck is the latest one; change DECK when a newer one should be the public one.

import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const DECK = { track: 'thesis', id: 'presentacion-09', title: { en: 'Midterm Pecha Kucha', es: 'Pecha Kucha de medio término' } }

const HERE = dirname(fileURLToPath(import.meta.url))
const PRESENTATIONS = resolve(HERE, '..', 'presentations')

/** `assets/site.js` for the public site: this deck alone, and no name of any other project. */
export const siteJs = (deck = DECK) => `// Generated by scripts/build-pages.mjs: the public site holds one deck.
export const APP_NAME = 'Research thesis'
export const TRACKS = { ${deck.track}: { en: 'IAAC', es: 'IAAC' } }
export const PRESENTATIONS = {
  ${deck.track}: [{ id: '${deck.id}', title: ${JSON.stringify(deck.title)} }],
}
`

/** The page that opens the deck, for the site's root. */
export const indexHtml = (deck = DECK) => `<!doctype html>
<meta charset="utf-8" />
<title>${deck.title.en}</title>
<meta http-equiv="refresh" content="0; url=${deck.track}/${deck.id}/" />
<link rel="canonical" href="${deck.track}/${deck.id}/" />
<p><a href="${deck.track}/${deck.id}/">${deck.title.en}</a></p>
`

/** Stages the site in `outDir` (emptied first) and returns the files it wrote, relative to it. */
export function buildPages(outDir, deck = DECK) {
  const source = join(PRESENTATIONS, deck.track, deck.id)
  if (!existsSync(join(source, 'index.html'))) throw new Error(`no deck at ${source}`)
  rmSync(outDir, { recursive: true, force: true })
  mkdirSync(join(outDir, deck.track), { recursive: true })
  cpSync(join(PRESENTATIONS, 'assets'), join(outDir, 'assets'), { recursive: true })
  cpSync(source, join(outDir, deck.track, deck.id), { recursive: true })
  // the decks' theme.js re-exports the map's (`../../assets/theme.js`); on the site that file sits beside it
  cpSync(join(PRESENTATIONS, '..', 'assets', 'theme.js'), join(outDir, 'assets', 'theme-core.js'))
  writeFileSync(join(outDir, 'assets', 'theme.js'), readFileSync(join(PRESENTATIONS, 'assets', 'theme.js'), 'utf8').replace("'../../assets/theme.js'", "'./theme-core.js'"))
  writeFileSync(join(outDir, 'assets', 'site.js'), siteJs(deck))
  writeFileSync(join(outDir, 'index.html'), indexHtml(deck))
  writeFileSync(join(outDir, '.nojekyll'), '') // the files are served as they are
  const walk = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)).map((f) => `${e.name}/${f}`) : [e.name]))
  return walk(outDir)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = resolve(process.argv[2] ?? join(HERE, '..', '..', '_site'))
  const files = buildPages(out)
  console.log(`wrote ${files.length} files to ${out}`)
}
